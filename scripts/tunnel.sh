#!/usr/bin/env bash
# Dev/test access without exposing anything but SSH:
#   1. On the k3s server node, a systemd unit (sf-forwards) runs `kubectl port-forward` loops against the
#      LOCAL API server, bound to the node's 127.0.0.1. Port-forward goes through the kubelet, so it works
#      for pods on any node and is not blocked by the namespaces' default-deny NetworkPolicies.
#   2. One self-healing SSH session forwards those node-local ports (and the API) to this machine.
# Much more stable than local `kubectl port-forward` on a flaky connection. Production access is via
# ingress + Cloudflare instead.
#
#   SSH_KEY=... SERVER_IP=... scripts/tunnel.sh            # runs until killed (reconnects forever)
#   SSH_KEY=... SERVER_IP=... scripts/tunnel.sh stop-node  # remove the node-side unit
source "$(dirname "$0")/lib/common.sh"
: "${SSH_KEY:?}" "${SERVER_IP:?}"
SSH_USER="${SSH_USER:-scalesafe}"
SSH_OPTS=(-i "$SSH_KEY" -o StrictHostKeyChecking=accept-new -o UserKnownHostsFile=/dev/null -o LogLevel=ERROR
          -o ConnectTimeout=15)
node() { ssh "${SSH_OPTS[@]}" "$SSH_USER@$SERVER_IP" "$@"; }

# local-port  namespace/service:port
FORWARDS="13000 e2e/gitea:3000
15000 e2e/registry:5000
18081 ci/el-github:8080
18080 argocd/argocd-server:80
19097 tekton-pipelines/tekton-dashboard:9097
18082 sample-app/sample-app:80
8180 scalesafe/keycloak:8080
8081 scalesafe/orchestrator:8080
8082 scalesafe/client-service:8080
8083 scalesafe/kyc-service:8080
8084 scalesafe/investor-service:8080
8085 scalesafe/verification-service:8080
8086 scalesafe/esign-service:8080
5173 scalesafe/web-app:8080
5174 scalesafe/web-admin:8080
8088 scalesafe/site:8080"

if [[ "${1:-}" == stop-node ]]; then
  node "sudo systemctl stop sf-forwards 2>/dev/null; sudo rm -f /usr/local/bin/sf-forwards.sh"; log "node unit removed"; exit 0
fi

# ---- node-side forwarder (node ports 21000, 21001, ... in list order - unique by construction)
remote="#!/bin/sh
# Generated by scripts/tunnel.sh - dev access port-forwards bound to 127.0.0.1 on this node.
"
ARGS=(-L 16443:127.0.0.1:6443)
idx=0
while read -r lport target; do
  ns="${target%%/*}"; svc="${target#*/}"; port="${svc##*:}"; svc="${svc%%:*}"
  rport=$((21000 + idx)); idx=$((idx + 1))
  remote+="(while true; do k3s kubectl -n $ns port-forward --address 127.0.0.1 svc/$svc $rport:$port >/dev/null 2>&1; sleep 3; done) &
"
  ARGS+=(-L "$lport:127.0.0.1:$rport")
done <<< "$FORWARDS"
remote+="wait
"
printf '%s' "$remote" | node "sudo tee /usr/local/bin/sf-forwards.sh >/dev/null && sudo chmod 755 /usr/local/bin/sf-forwards.sh &&
  (sudo systemctl stop sf-forwards 2>/dev/null; sudo systemctl reset-failed sf-forwards 2>/dev/null;
   sudo systemd-run --unit sf-forwards --collect -p Restart=always /usr/local/bin/sf-forwards.sh >/dev/null)" ||
  die "could not install node-side forwarder"
log "node-side forwarder running ($(( ${#ARGS[@]} / 2 - 1 )) services)"

while true; do
  log "tunnel up"
  ssh -N "${SSH_OPTS[@]}" -o ServerAliveInterval=15 -o ServerAliveCountMax=3 -o ExitOnForwardFailure=yes \
    "${ARGS[@]}" "$SSH_USER@$SERVER_IP"
  warn "tunnel dropped - reconnecting"
  sleep 3
done
